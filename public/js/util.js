export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

export function h(html) {
  const t = document.createElement("template");
  t.innerHTML = html.trim();
  return t.content.firstElementChild;
}

export const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

export function debounce(fn, ms) {
  let t;
  return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
}

export const uid = () => Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4);

// ---- Markdown with KaTeX ----
// Math is pulled out before marked runs (so `_` and `*` inside math survive), then rendered back in.
marked.setOptions({ gfm: true, breaks: false });
export function md(text) {
  const math = [];
  const stash = (tex, display) => `\u0000${math.push({ tex, display }) - 1}\u0000`;
  let src = String(text || "")
    .replace(/\$\$([\s\S]+?)\$\$/g, (_, t) => stash(t, true))
    .replace(/\\\[([\s\S]+?)\\\]/g, (_, t) => stash(t, true))
    .replace(/\\\(([\s\S]+?)\\\)/g, (_, t) => stash(t, false))
    .replace(/(^|[^\\$])\$([^\s$](?:[^$\n]*?[^\s$])?)\$(?!\d)/g, (_, pre, t) => pre + stash(t, false));
  // An unterminated $$ while streaming: hide the partial math instead of showing raw source.
  src = src.replace(/\$\$[\s\S]*$/, "");
  let html = marked.parse(src);
  html = html.replace(/\u0000(\d+)\u0000/g, (_, i) => {
    const { tex, display } = math[i];
    try { return katex.renderToString(tex, { displayMode: display, throwOnError: false, output: "html" }); }
    catch { return esc(tex); }
  });
  return html;
}

// ---- Streaming text from the server ----
// Calls onText(fullTextSoFar) at most once per animation frame. Returns the final text.
export async function stream(task, body, onText, { signal } = {}) {
  const res = await fetch(`/api/ai/stream/${task}`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body), signal });
  if (!res.ok) throw new Error((await res.json().catch(() => ({}))).error || res.statusText);
  const reader = res.body.getReader();
  const dec = new TextDecoder();
  let full = "", queued = false;
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    full += dec.decode(value, { stream: true });
    if (!queued) { queued = true; requestAnimationFrame(() => { queued = false; onText(full); }); }
  }
  onText(full);
  return full;
}

export async function aiJson(task, body) {
  const res = await fetch(`/api/ai/json/${task}`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
  const data = await res.json();
  if (!res.ok) throw new Error(data.error || res.statusText);
  return data;
}

export function toast(msg, ms = 1800) {
  let t = $("#toast");
  if (!t) { t = h(`<div id="toast"></div>`); document.body.append(t); }
  t.textContent = msg;
  t.classList.add("show");
  clearTimeout(t._timer);
  t._timer = setTimeout(() => t.classList.remove("show"), ms);
}

